type StaffIconButtonProps = {
  label: string;
  title?: string;
  onClick?: () => void;
  type?: "button" | "submit";
  disabled?: boolean;
  tone?: "default" | "edit" | "danger" | "muted";
  children: ReactNode;
  className?: string;
};

export function StaffIconButton({
  label,
  title,
  onClick,
  type = "button",
  disabled,
  tone = "default",
  children,
  className = "",
}: StaffIconButtonProps) {
  return (
    <button
      type={type}
      className={`staff-icon-btn staff-icon-btn-${tone}${className ? ` ${className}` : ""}`}
      aria-label={label}
      title={title ?? label}
      onClick={onClick}
      disabled={disabled}
    >
      {children}
    </button>
  );
}
